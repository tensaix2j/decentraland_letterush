/**
 * Compiles a plain-text word list into src/data/dictionary-data.ts.
 *
 *   npm run gen:dict                      # reads assets/wordlist.txt
 *   npm run gen:dict -- path/to/list.txt  # or any other file
 *   npm run gen:dict -- list.txt --max 15 # keep words up to 15 letters
 *
 * Input format: one word per line. Case, surrounding whitespace, CRLF endings,
 * blank lines, duplicates and `#` comment lines are all handled. Anything
 * containing a character outside a-z (digits, hyphens, apostrophes, accents) is
 * dropped and reported, so you can see exactly what was rejected.
 *
 * The scene runs in QuickJS and cannot read files at runtime, so the list has to
 * be baked into the bundle. It is stored front-coded — each entry is one marker
 * character giving the shared prefix length with the previous word, then that
 * word's suffix — which roughly halves the size of a sorted list.
 * src/dictionary.ts expands it lazily on first use into one fixed-width string
 * per word length and binary searches that.
 *
 * The marker is UPPERCASE 'A'+n and suffixes are lowercase, so the two alphabets
 * are disjoint and the decoder can tell where each entry ends. (Base36 markers
 * would collide: a shared prefix of 10 encodes as 'a', which is also a valid
 * suffix character. That only shows up once words exceed 10 letters.)
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const args = process.argv.slice(2)
const flagIndex = args.findIndex((a) => a.startsWith('--'))
const positional = flagIndex === -1 ? args : args.slice(0, flagIndex)
const readFlag = (name, fallback) => {
  const i = args.indexOf(`--${name}`)
  return i === -1 ? fallback : Number(args[i + 1])
}

const SOURCE = resolve(ROOT, positional[0] || 'assets/wordlist.txt')
const MIN_LEN = readFlag('min', 2)
const MAX_LEN = readFlag('max', 15)
const OUT = resolve(ROOT, 'src/data/dictionary-data.ts')

if (!existsSync(SOURCE)) {
  console.error(
    `No word list at ${SOURCE}\n` +
      `Put one word per line in assets/wordlist.txt, or pass a path:\n` +
      `  npm run gen:dict -- path/to/list.txt`
  )
  process.exit(1)
}

const raw = readFileSync(SOURCE, 'utf8').split(/\r?\n/)

const words = new Set()
const rejected = { tooShort: 0, tooLong: 0, badChars: [] }

for (const line of raw) {
  const trimmed = line.trim()
  if (!trimmed || trimmed.startsWith('#')) continue
  const word = trimmed.toLowerCase()
  if (!/^[a-z]+$/.test(word)) {
    if (rejected.badChars.length < 12) rejected.badChars.push(trimmed)
    continue
  }
  if (word.length < MIN_LEN) {
    rejected.tooShort++
    continue
  }
  if (word.length > MAX_LEN) {
    rejected.tooLong++
    continue
  }
  words.add(word)
}

const sorted = Array.from(words).sort()
if (!sorted.length) {
  console.error('Word list produced zero usable words — check the input format.')
  process.exit(1)
}

// Front-code. Marker = uppercase 'A' + sharedPrefixLength, suffix = lowercase.
// Capped at 25 so the marker is always a single character in A-Z.
const PREFIX_CAP = 25
const encoded = []
let prev = ''
for (const word of sorted) {
  let shared = 0
  const limit = Math.min(prev.length, word.length, PREFIX_CAP)
  while (shared < limit && prev[shared] === word[shared]) shared++
  encoded.push(String.fromCharCode(65 + shared) + word.slice(shared))
  prev = word
}
const packed = encoded.join('')

// Round-trip the encoding before writing, so a broken list can never ship.
// This is what caught the base36 marker collision — keep it.
{
  const out = []
  let previous = ''
  let i = 0
  while (i < packed.length) {
    const shared = packed.charCodeAt(i) - 65
    i++
    let j = i
    while (j < packed.length && packed.charCodeAt(j) >= 97 && packed.charCodeAt(j) <= 122) j++
    const word = previous.slice(0, shared) + packed.slice(i, j)
    i = j
    previous = word
    out.push(word)
  }
  if (out.length !== sorted.length || out.some((w, k) => w !== sorted[k])) {
    const bad = out.findIndex((w, k) => w !== sorted[k])
    console.error(
      `Front-coding round-trip failed — refusing to write.\n` +
        `  decoded ${out.length} words, expected ${sorted.length}\n` +
        (bad >= 0 ? `  first mismatch at ${bad}: got "${out[bad]}", want "${sorted[bad]}"` : '')
    )
    process.exit(1)
  }
}

const lengths = {}
for (const w of sorted) lengths[w.length] = (lengths[w.length] || 0) + 1

const CHUNK = 200
const lines = []
for (let i = 0; i < packed.length; i += CHUNK) {
  lines.push('  ' + JSON.stringify(packed.slice(i, i + CHUNK)))
}

const ts =
  `// AUTO-GENERATED by tools/gen-dictionary.mjs — do not edit by hand.\n` +
  `// Source: ${positional[0] || 'assets/wordlist.txt'} (${sorted.length} words, lengths ${MIN_LEN}-${MAX_LEN}).\n` +
  `// Format: each entry is one UPPERCASE marker char ('A' + shared prefix length\n` +
  `// with the previous word) followed by that word's lowercase suffix. The two\n` +
  `// alphabets are disjoint so the decoder knows where each entry ends.\n` +
  `// Expanded lazily by src/dictionary.ts.\n` +
  `export const DICT_MIN_LEN = ${MIN_LEN}\n` +
  `export const DICT_MAX_LEN = ${MAX_LEN}\n` +
  `export const DICT_WORD_COUNT = ${sorted.length}\n` +
  `export const DICT_PACKED: string =\n` +
  lines.join(' +\n') +
  '\n'

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, ts)

const rawBytes = sorted.join('\n').length
console.log(`Source        ${SOURCE}`)
console.log(`Words kept    ${sorted.length}`)
console.log(
  `By length     ${Object.keys(lengths)
    .sort((a, b) => a - b)
    .map((k) => `${k}:${lengths[k]}`)
    .join('  ')}`
)
console.log(
  `Size          ${(rawBytes / 1024).toFixed(0)} KB raw -> ${(packed.length / 1024).toFixed(0)} KB packed`
)
if (rejected.tooShort || rejected.tooLong) {
  console.log(`Dropped       ${rejected.tooShort} too short, ${rejected.tooLong} too long`)
}
if (rejected.badChars.length) {
  console.log(`Non a-z       ${rejected.badChars.join(', ')}${rejected.badChars.length >= 12 ? ' ...' : ''}`)
}
if (packed.length > 900 * 1024) {
  console.log(
    `\nHeads up: that is a large bundle addition. Consider --max 12 if scene load feels slow.`
  )
}
console.log(`\nWrote ${OUT}`)
